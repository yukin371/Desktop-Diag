//go:build windows

package collect

// 采集器的注册顺序就是执行顺序，**不能随意调换**：
//
//  1. 主机与系统信息 —— 报告头需要它；且后续采集的失败原因要靠 IsAdmin
//     来解释（"因权限不足未采集"这句话只有在知道了是不是管理员之后才敢说）。
//  2. 网络适配器信息 —— 判定引擎必须先看到 Adapters，才能把后面的探测结果
//     归属到具体网卡上，并据此区分"哪块网卡有问题"与"整机都没网"。
//  3. 系统健康度 —— CPU 采样需要 1 秒，放在探测之前可以让这段时间与
//     探测的等待重叠不起来……恰恰相反，它必须独占这 1 秒：
//     否则采样窗口里混入探测自身的 CPU 开销，测出来的是本工具自己。
//  4. 网络连通性探测 —— 最后执行，因为它依赖前三者的产出。
//
// 整个 init 里只有这一处注册列表，是为了让"顺序"这件事只有一个可改的地方：
// 把注册散落在各文件里，下次有人新增采集域时就只能靠猜。
func init() {
	Register(systemCollector{})
	Register(networkCollector{})
	Register(healthCollector{})
	Register(probeCollector{})
}
